/**
 * Golden replays: fixtures/<name>.rrpl, fixtures/witness.json (the state hash every 100 ticks plus
 * the final result) and fixtures/golden.ts (base64, for the WebView /dev/sim check).
 *   pnpm --filter @realm/battle-engine make-golden        → (re)writes the CURRENT version's goldens
 *   pnpm --filter @realm/battle-engine make-golden --v1   → rewrites the frozen v1 goldens (never needed)
 * Existing entries for other versions are kept untouched. Re-run only when the rules change ON PURPOSE.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bytesToBase64, createBattle, encodeReplay, replayHash, resultOf, stateHash, step, ENGINE_VERSION, type BattleInput } from '../src';
import { goldenInputs, goldenInputsV2 } from '../test/golden-inputs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'fixtures');
mkdirSync(out, { recursive: true });

const v1 = process.argv.includes('--v1');
const sets: [string, BattleInput[]][] = v1 ? [['golden', goldenInputs()]] : [[`golden-v${ENGINE_VERSION}`, goldenInputsV2()]];

const witnessPath = join(out, 'witness.json');
const witness: Record<string, unknown> = existsSync(witnessPath) ? JSON.parse(readFileSync(witnessPath, 'utf8')) : {};
const inlinePath = join(out, 'golden.ts');
const inline: Record<string, string> = existsSync(inlinePath)
  ? JSON.parse(readFileSync(inlinePath, 'utf8').replace(/^[\s\S]*?= /, '').replace(/;\s*$/, ''))
  : {};

for (const [prefix, inputs] of sets)
  inputs.forEach((input, i) => {
    const name = `${prefix}-${i + 1}`;
    const bytes = encodeReplay(input);
    writeFileSync(join(out, `${name}.rrpl`), bytes);
    inline[name] = bytesToBase64(bytes);
    const state = createBattle(input);
    const hashes: string[] = [];
    while (!state.ended) {
      step(state);
      if (state.tick % 100 === 0) hashes.push(stateHash(state));
    }
    const r = resultOf(state);
    witness[name] = {
      engineVersion: input.engineVersion,
      replayHash: replayHash(bytes),
      stars: r.stars,
      destructionBp: r.destructionBp,
      ticks: r.ticks,
      endReason: r.endReason,
      finalStateHash: r.stateHash,
      every100: hashes,
    };
    console.log(name, `v${input.engineVersion}`, `${r.stars}★`, r.destructionBp, r.endReason, replayHash(bytes), r.stateHash);
  });
writeFileSync(witnessPath, JSON.stringify(witness, null, 2) + '\n');
writeFileSync(inlinePath, `// Generated by scripts/make-golden.ts — do not edit.\nexport const GOLDEN_REPLAYS: Record<string, string> = ${JSON.stringify(inline, null, 2)};\n`);
